import assert from 'node:assert/strict';
import {describeToken, networkShapes} from '../src/token-state.mjs';
const token=describeToken({axes:6,axis:2,patch:31,dim:384,mode:'random',maskedIndices:[95]});
assert.deepEqual(token.points,[124,125,126,127]);
assert.equal(token.axisName,'acc Z');
assert.equal(token.timeIndex,31);
assert.equal(token.dimension,384);
assert.equal(token.masked,true);
assert.equal(token.total,192);
const inference=networkShapes({axes:6,mode:'inference',masked:0});
assert.equal(inference.visible,192);
assert.deepEqual(inference.shapes.map(x=>x.shape),['[B, 6, 128]','[B, 192, 384]','[B, 192, 384]','[B, 192, 384]','[B, 384]','[B, 7]']);
const pretrain=networkShapes({axes:6,mode:'random',masked:125});
assert.equal(pretrain.visible,67);
assert.deepEqual(pretrain.shapes.map(x=>x.shape),['[B, 6, 128]','[B, 192, 384]','[B, 67, 384]','[B, 67, 384]','[B, 192, 192]','[B, 192, 4]']);
const tri=networkShapes({axes:3,mode:'time',masked:63});
assert.equal(tri.total,96);
assert.equal(tri.visible,33);
assert.equal(describeToken({axes:3,axis:1,patch:0,dim:1,mode:'inference',maskedIndices:[32]}).masked,false);
console.log('token indexing, masking, and train/inference shapes passed');
